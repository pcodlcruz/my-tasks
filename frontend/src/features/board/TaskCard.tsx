import { missionErrorMessage, useSetMission } from '../../api/progress'
import { useCompleteTask, useTogglePin, useTrashTask } from '../../api/tasks'
import type { Task } from '../../api/types'
import { useToastStore } from '../../stores/toastStore'
import { MAX_MISSION_TASKS } from '../progress/MissionPicker'
import { pendingSince } from '../schedules/recurrenceLabel'
import { ScopeBadge } from '../shared/TaskBadges'

interface TaskCardProps {
  task: Task
  onEdit: (task: Task) => void
  // Today's mission; `undefined` if the progress could not be loaded (no mission button then).
  missionTaskIds?: string[]
  // The progress day today is; `undefined` if the progress could not be loaded (a scheduled task
  // then shows no "pending since").
  today?: string
}

const TEXT_BUTTON =
  'rounded p-1 text-caption text-text-muted hover:bg-surface-alt hover:text-text disabled:cursor-not-allowed disabled:opacity-60'

// Spacing comes from the density variables (src/index.css). Compact lays the card out in one
// row (title and actions, then scope and "Completar") so more tasks fit in the same height.
const ARTICLE =
  'rounded-lg border border-border bg-surface p-[var(--card-padding)] shadow-sm compact:flex compact:flex-wrap compact:items-center compact:gap-x-3'
const HEADER =
  'flex flex-col gap-2 sm:flex-row sm:items-start sm:justify-between compact:min-w-0 compact:flex-1 compact:items-center'
const FOOTER =
  'mt-[var(--card-inner-gap)] flex items-center justify-between border-t border-border/60 pt-[var(--card-footer-gap)] compact:mt-0 compact:shrink-0 compact:gap-3 compact:border-t-0 compact:pt-0'

export function TaskCard({ task, onEdit, missionTaskIds, today }: TaskCardProps): JSX.Element {
  const { togglePin, isPending: isPinPending } = useTogglePin()
  const complete = useCompleteTask()
  const trash = useTrashTask()
  const setMission = useSetMission()
  const inMission = missionTaskIds?.includes(task.id) ?? false
  const missionFull = (missionTaskIds?.length ?? 0) >= MAX_MISSION_TASKS
  const reasonId = `mission-full-${task.id}`
  // Generated by a schedule; "pending since" when that day went by and it is still active.
  const isScheduled = task.schedule_id !== null
  const pendingFrom =
    isScheduled && task.scheduled_for !== null && today !== undefined && task.scheduled_for < today
      ? task.scheduled_for
      : null

  // The whole mission is sent: the current one with this task added or taken out. Nothing changes
  // on screen until the server accepts it.
  function toggleMission(): void {
    if (missionTaskIds === undefined) return
    const next = inMission
      ? missionTaskIds.filter((id) => id !== task.id)
      : [...missionTaskIds, task.id]
    setMission.mutate(next, {
      onError: (error) => useToastStore.getState().show(missionErrorMessage(error)),
    })
  }

  return (
    <article className={ARTICLE}>
      <div className={HEADER}>
        <p className="flex min-w-0 items-center gap-1.5 break-words text-body font-semibold text-text">
          {task.pinned && (
            <span aria-label="Fijada" title="Fijada">
              📌
            </span>
          )}
          {task.title}
        </p>
        {isScheduled && (
          <p className="flex shrink-0 flex-wrap items-center gap-1 text-caption font-semibold text-text-muted">
            <svg
              aria-hidden="true"
              viewBox="0 0 24 24"
              fill="none"
              stroke="currentColor"
              strokeWidth="2"
              strokeLinecap="round"
              strokeLinejoin="round"
              className="h-3.5 w-3.5"
            >
              <rect x="3" y="4" width="18" height="18" rx="2" />
              <line x1="16" y1="2" x2="16" y2="6" />
              <line x1="8" y1="2" x2="8" y2="6" />
              <line x1="3" y1="10" x2="21" y2="10" />
            </svg>
            <span>Programada</span>
            {pendingFrom !== null && (
              <>
                <span aria-hidden="true">·</span>
                <span className="font-normal">Pendiente desde el {pendingSince(pendingFrom)}</span>
              </>
            )}
          </p>
        )}
        {inMission && (
          <p className="flex shrink-0 items-center gap-1 text-caption font-semibold text-gold">
            <span aria-hidden="true">★</span>
            <span>Misión del día</span>
          </p>
        )}
        <div className="flex shrink-0 flex-wrap items-center gap-1 sm:justify-end">
          <button
            type="button"
            onClick={() => void togglePin(task)}
            disabled={isPinPending}
            className={TEXT_BUTTON}
          >
            {task.pinned ? 'Desfijar' : 'Fijar'}
          </button>
          <button type="button" onClick={() => onEdit(task)} className={TEXT_BUTTON}>
            Editar
          </button>
          {missionTaskIds !== undefined && (
            <>
              <button
                type="button"
                onClick={toggleMission}
                disabled={setMission.isPending || (!inMission && missionFull)}
                aria-describedby={!inMission && missionFull ? reasonId : undefined}
                className={TEXT_BUTTON}
              >
                {inMission ? 'Quitar de la misión' : 'Añadir a la misión'}
              </button>
              {!inMission && missionFull && (
                <span id={reasonId} className="sr-only">
                  La misión ya tiene 5 tareas.
                </span>
              )}
            </>
          )}
          <button
            type="button"
            onClick={() => trash.mutate(task.id)}
            disabled={trash.isPending}
            className={TEXT_BUTTON}
          >
            Mover a la papelera
          </button>
        </div>
      </div>
      <div className={FOOTER}>
        <ScopeBadge scope={task.scope} />
        <button
          type="button"
          onClick={() => complete.mutate(task.id)}
          disabled={complete.isPending}
          className="rounded-lg border border-success/40 px-3 py-1 text-caption font-semibold text-success hover:bg-success/10 disabled:cursor-not-allowed disabled:opacity-60"
        >
          Completar
        </button>
      </div>
    </article>
  )
}
